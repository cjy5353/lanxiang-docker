import assert from 'node:assert/strict';
import {database} from './support.mjs';
const pg=await database();
const hash='a'.repeat(64);
await pg.query('insert into public.lx_codes(hash,label,created) values($1,$2,$3)',[hash,'TEST',Date.now()]);
const nonce=crypto.randomUUID();
const run=n=>pg.query('select public.lx_start_test($1,$2,$3) as r',[hash,n,Date.now()]);
const first=(await run(nonce)).rows[0].r;
assert.equal((await run(nonce)).rows[0].r.sessionId,first.sessionId);
const attempts=await Promise.all(Array.from({length:8},()=>run(crypto.randomUUID())));
assert.equal(attempts.filter(r=>r.rows[0].r.sessionId).length,2);
assert.equal(attempts.filter(r=>r.rows[0].r.error==='quota').length,6);
const count=await pg.query('select count(*) as n from public.lx_sessions');assert.equal(Number(count.rows[0].n),3);
const result={id:crypto.randomUUID(),name:'original'};
await pg.query('select public.lx_save_result($1,$2)',[first.sessionId,JSON.stringify(result)]);
const repeated=await pg.query('select public.lx_save_result($1,$2) as r',[first.sessionId,JSON.stringify({id:crypto.randomUUID(),name:'changed'})]);assert.deepEqual(repeated.rows[0].r,result);
await pg.exec('set role anon;');
await assert.rejects(pg.query('select * from public.lx_codes'),/permission denied/);
await assert.rejects(pg.query('select public.lx_start_test($1,$2,$3)',[hash,crypto.randomUUID(),Date.now()]),/permission denied/);
await pg.exec('reset role; set role authenticated;');
await assert.rejects(pg.query('select * from public.lx_sessions'),/permission denied/);
await pg.exec('reset role;');
const protectedTables=await pg.query("select relname,relrowsecurity from pg_class where relname in ('lx_codes','lx_sessions','lx_limits')");assert(protectedTables.rows.every(t=>t.relrowsecurity));
await pg.close();
console.log('PASS: PostgreSQL migration, quota and immutable result functions, restricted table/RPC grants, RLS enabled. Parallel calls use one PGlite connection; remote multi-connection verification remains required.');
